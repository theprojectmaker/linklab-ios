// Regenerates src/lib/broadDomains.ts from the public Majestic Million ranking.
// Usage:
//   curl -o majestic_million.csv https://downloads.majestic.com/majestic_million.csv
//   node scripts/gen-broad-domains.js majestic_million.csv
//
// Majestic Million (https://majestic.com/reports/majestic-million) is a
// standard, openly published top-domains ranking used throughout the
// security/networking industry — not a proxy list, provides no working
// proxy. Domains already covered by the curated anchors in destinations.ts
// are excluded to avoid duplicate hosts.
const fs = require('fs');
const path = require('path');

const csvPath = process.argv[2];
if (!csvPath) {
  console.error('Usage: node gen-broad-domains.js <majestic_million.csv>');
  process.exit(1);
}

const destPath = path.join(__dirname, '..', 'src', 'lib', 'destinations.ts');
const outPath = path.join(__dirname, '..', 'src', 'lib', 'broadDomains.ts');

const csv = fs.readFileSync(csvPath, 'utf8');
const lines = csv.split('\n').slice(1, 5001); // top 5000 rows
const existing = new Set(
  (fs.readFileSync(destPath, 'utf8').match(/host: '([^']+)'/g) || []).map((s) => s.slice(7, -1))
);

const out = [];
const seen = new Set();
for (const line of lines) {
  if (!line.trim()) continue;
  const domain = line.split(',')[2];
  if (!domain || existing.has(domain) || seen.has(domain)) continue;
  seen.add(domain);
  out.push(domain);
}

const header = `// Auto-generated by scripts/gen-broad-domains.js from the public Majestic
// Million top-domains ranking (https://majestic.com/reports/majestic-million).
// NOT a proxy list; provides no working proxy. Same trust model as any
// ordinary site-categorization/firewall test. Entries already covered by the
// curated anchors in destinations.ts are excluded.
export const BROAD_DOMAINS: string[] = ${JSON.stringify(out)};
`;

fs.writeFileSync(outPath, header);
console.log(`Wrote ${out.length} domains to ${outPath}`);
